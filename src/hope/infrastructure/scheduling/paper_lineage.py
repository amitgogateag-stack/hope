def _verify_staged_signal_lineage(
    connection: Connection,
    effects: tuple[PaperEffect, ...],
) -> bool:
    """Authenticate every independent signal emitted by one decision job."""
    if (
        not effects
        or any(
            not isinstance(effect, PaperEffect)
            or effect.effect_type is not PaperEffectType.SIGNAL
            for effect in effects
        )
        or len({effect.effect_id for effect in effects}) != len(effects)
        or len({effect.entity_id for effect in effects}) != len(effects)
        or len({effect.job_run_id for effect in effects}) != 1
    ):
        return False

    metadata = MetaData()
    signals = Table(
        "signals",
        metadata,
        Column("signal_id", Uuid, primary_key=True),
        Column("instrument_id", Uuid, nullable=False),
        Column("decision_time", DateTime(timezone=True), nullable=False),
        Column("state", String, nullable=False),
        Column("strategy_version", String),
        Column("signal_type", String),
        Column("conviction", Numeric),
        Column("inputs_hash", String),
    )
    for effect in effects:
        row = connection.execute(
            select(
                signals.c.instrument_id,
                signals.c.decision_time,
                signals.c.state,
                signals.c.strategy_version,
                signals.c.signal_type,
                signals.c.conviction,
                signals.c.inputs_hash,
            ).where(signals.c.signal_id == effect.entity_id)
        ).mappings().one_or_none()
        if row is None or row["state"] != "SIGNAL":
            return False
        try:
            signal = Signal(
                signal_id=effect.entity_id,
                instrument_id=row["instrument_id"],
                strategy_version=row["strategy_version"],
                decision_time=row["decision_time"],
                signal_type=row["signal_type"],
                conviction=row["conviction"],
                inputs_hash=row["inputs_hash"],
            )
        except (TypeError, ValueError):
            return False
        if effect.payload_hash != paper_signal_payload_hash(signal):
            return False
    return True


def _verify_no_trade_lineage(
    connection: Connection,
    effect: PaperEffect,
) -> bool:
    if effect.effect_type is not PaperEffectType.NO_TRADE:
        return False
    metadata = MetaData()
    decisions = Table(
        "paper_no_trade_decisions",
        metadata,
        Column("decision_id", Uuid, primary_key=True),
        Column("job_run_id", Uuid, nullable=False),
        Column("strategy_version", String, nullable=False),
        Column("decision_time", DateTime(timezone=True), nullable=False),
        Column("inputs_hash", String, nullable=False),
    )
    row = connection.execute(
        select(decisions).where(decisions.c.decision_id == effect.entity_id)
    ).mappings().one_or_none()
    if row is None or row["job_run_id"] != effect.job_run_id:
        return False
    try:
        decision = PaperNoTradeDecision(
            decision_id=row["decision_id"],
            strategy_version=row["strategy_version"],
            decision_time=row["decision_time"],
            inputs_hash=row["inputs_hash"],
        )
    except (TypeError, ValueError):
        return False
    return effect.payload_hash == paper_no_trade_payload_hash(decision)


def _verify_partial_fill_cancellation(
    connection: Connection,
    terminal_events: Table,
    cancellation_effect: PaperEffect,
    order_id: UUID,
    signal_id: UUID,
    order: Order,
    fill: Fill,
) -> bool:
    """Authenticate the remaining quantity and terminal payload for either PNL path."""
    if cancellation_effect.entity_id != order_id:
        return False
    terminal = connection.execute(
        select(
            terminal_events.c.outcome,
            terminal_events.c.reason_code,
            terminal_events.c.event_time,
            terminal_events.c.cancelled_quantity,
        ).where(terminal_events.c.order_id == order_id)
    ).mappings().one_or_none()
    if (
        terminal is None
        or terminal["outcome"] != "CANCELLED"
        or terminal["event_time"] < fill.fill_time
        or terminal["cancelled_quantity"] != order.quantity - fill.quantity
    ):
        return False
    try:
        cancellation = ExecutionCancellation(
            order_id,
            signal_id,
            order.instrument_id,
            Environment.PAPER,
            terminal["reason_code"],
            terminal["event_time"],
            terminal["cancelled_quantity"],
        )
    except (TypeError, ValueError):
        return False
    return cancellation_effect.payload_hash == paper_terminal_payload_hash(cancellation)


def _hydrate_staged_fill_accounting_lineage(
    connection: Connection,
    effects: tuple[PaperEffect, ...],
) -> tuple[PaperEffect, ...] | None:
    """Authenticate cross-job sources for one atomic FILL + PNL stage."""
    by_type = {effect.effect_type: effect for effect in effects}
    if set(by_type) != {PaperEffectType.FILL, PaperEffectType.PNL}:
        return None

    metadata = MetaData()
    fills = Table(
        "fills",
        metadata,
        Column("fill_id", Uuid, primary_key=True),
        Column("order_id", Uuid, nullable=False),
    )
    orders = Table(
        "orders",
        metadata,
        Column("order_id", Uuid, primary_key=True),
        Column("signal_id", Uuid, nullable=False),
    )
    dependency = connection.execute(
        select(
            fills.c.order_id,
            orders.c.signal_id,
        )
        .select_from(fills.join(orders, fills.c.order_id == orders.c.order_id))
        .where(fills.c.fill_id == by_type[PaperEffectType.FILL].entity_id)
    ).mappings().one_or_none()
    if dependency is None:
        return None

    repository = SqlAlchemyPaperEffectRepository(connection)
    try:
        sources = (
            repository.get_recoverable(
                PaperEffectType.SIGNAL, dependency["signal_id"]
            ),
            repository.get_recoverable(
                PaperEffectType.RISK, dependency["signal_id"]
            ),
            repository.get_recoverable(
                PaperEffectType.ORDER, dependency["order_id"]
            ),
        )
    except ValueError:
        return None
    if any(source is None for source in sources):
        return None
    return tuple(source for source in sources if source is not None) + effects


def _hydrate_staged_entry_lineage(
    connection: Connection,
    effects: tuple[PaperEffect, ...],
) -> tuple[PaperEffect, ...] | None:
    """Authenticate the succeeded SIGNAL source for one RISK + ORDER stage."""
    by_type = {effect.effect_type: effect for effect in effects}
    if set(by_type) != {PaperEffectType.RISK, PaperEffectType.ORDER}:
        return None

    signal_id = by_type[PaperEffectType.RISK].entity_id
    order_id = by_type[PaperEffectType.ORDER].entity_id
    metadata = MetaData()
    orders = Table(
        "orders",
        metadata,
        Column("order_id", Uuid, primary_key=True),
        Column("signal_id", Uuid, nullable=False),
    )
    dependency = connection.execute(
        select(orders.c.signal_id).where(orders.c.order_id == order_id)
    ).mappings().one_or_none()
    if dependency is None or dependency["signal_id"] != signal_id:
        return None

    try:
        source = SqlAlchemyPaperEffectRepository(connection).get_recoverable(
            PaperEffectType.SIGNAL, signal_id
        )
    except ValueError:
        return None
    if source is None:
        return None
    return (source,) + effects


